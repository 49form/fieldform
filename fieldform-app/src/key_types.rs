pub fn type_of(op: &str, key: &str) -> Option<&'static str> {
    TYPES.iter().find(|(o, k, _)| *o == op && *k == key).map(|(_, _, t)| *t)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_key_types_match_the_blocks() {
        let derived = crate::console_keys::tests::derived_key_types();
        if std::env::var_os("FIELDFORM_PRINT_KEY_TYPES").is_some() {
            for ((op, key), ty) in &derived {
                println!("    ({op:?}, {key:?}, {ty:?}),");
            }
        }
        let written: std::collections::BTreeMap<(String, String), &str> =
            TYPES.iter().map(|(o, k, t)| ((o.to_string(), k.to_string()), *t)).collect();
        assert_eq!(written, derived, "regenerate TYPES (see the module note)");
    }
}
